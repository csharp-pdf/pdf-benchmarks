"""Writes the "Latest results" section of a README from one benchmark run, so the headline numbers sit on the
repository's front page instead of only in results/.

    python analysis/readme_summary.py --run 2026-10-15 --readme README.md [--readme ../pdf-libraries-compared/README.md]
        [--override windows:pdfsharp=2026-10-15-pdfsharp-windows ...]   (as for report.py)
        [--html <SelectPdf.Web>/Pages/Comparisons]   (the same tables and leaders as Razor partials for the site)
        [--llms <SelectPdf.Web>/BenchmarkFacts/llms.md]   (the leaders as sentences for the site's llms.txt)

Everything between the two marker lines below is replaced. The tables summarise the results page of the run (same
data, same overrides); the list names the leader of each measure, whoever it is. Nothing is scored or ranked overall.
"""
import argparse
import pathlib
import statistics

import pair_sections
import report

START = "<!-- latest-results: generated by analysis/readme_summary.py, do not edit -->"
END = "<!-- /latest-results -->"
RESULTS_PAGE = "https://github.com/csharp-pdf/pdf-libraries-compared/blob/main/benchmarks/{run}.md"
TOOLS = ("extract", "search", "rasterize", "word", "redact", "merge", "split", "watermark", "sign", "fill", "einvoice")


def build(run: report.Run, run_name: str):
    """Returns the README section (Markdown) and the same tables and leaders as data, for --html."""
    fmt = report.fmt
    data = {"run": run_name, "leaders": []}
    pk = run.packages("windows")
    libs = sorted(pk, key=lambda l: pk[l]["library"].lower())
    name = {l: pk[l]["library"] for l in libs}
    version = {l: next(iter(pk[l]["packages"].values()), "") for l in libs}
    v = {l: pair_sections.values(run, l) for l in libs}
    html = [l for l in libs if any(v[l][("speed", o)] for o in report.OSES)]

    # Speed: geometric mean over the pages every HTML library converted on that OS, so the means are comparable.
    common = {}
    for o in report.OSES:
        sets = [set(v[l][("speed", o)]) for l in html if v[l][("speed", o)]]
        common[o] = sorted(set.intersection(*sets)) if sets else []

    def speed(l, o):
        s = v[l][("speed", o)]
        return statistics.geometric_mean([s[f] for f in common[o]]) if s and common[o] and all(f in s for f in common[o]) else None

    def tp8(l, o):
        return v[l][("tp", o)].get(("sync", "8"))

    def growth(l, o):
        st = v[l][("stab", o)]
        return report.num(st[-1]["pss_mb"]) - report.num(st[0]["pss_mb"]) if st else None

    def checks(l, o):
        c = v[l][("checks", o)]
        return c if c[1] else None

    def pair(a, b, f=lambda x: fmt(x)):
        return f"{f(a) if a is not None else '–'} / {f(b) if b is not None else '–'}"

    def docker(l):
        rows = {r["variant"]: r for r in v[l]["deploy"]}
        m = rows.get("minimal")
        if m is None:
            return "–"
        if report.ok(m["root_ok"]) and report.ok(m["non_root_ok"]):
            return "runs on the plain .NET image"
        d = rows.get("documented")
        if d is not None and d["root_ok"] != "build failed" and report.ok(d["root_ok"]) and report.ok(d["non_root_ok"]):
            n = int(d["extra_os_packages"])
            packages = f"{n} OS package{'' if n == 1 else 's'} (vendor docs)"
            return (f"root only; non-root needs {packages}" if report.ok(m["root_ok"]) else f"needs {packages}")
        if report.ok(m["root_ok"]):
            return "runs as root only"
        if d is not None and d["root_ok"] == "build failed":
            return "does not run; the documented image does not build"
        return "does not run on the plain .NET image"

    out = [START, "",
           "## Latest results", "",
           f"Run of {run_name}: all ten libraries at their latest versions, on one machine under Windows and Linux. Every number comes from "
           f"the raw data in [`results/`](https://github.com/csharp-pdf/pdf-benchmarks/tree/main/results); the "
           f"[full results page]({RESULTS_PAGE.format(run=run_name)}) has every page, every measure and the failed "
           f"checks. There is no overall score.", ""]

    out += ["### HTML to PDF", "",
            f"Speed: geometric mean of the median times for the {len(common['windows'])} pages every HTML library converted "
            f"(Linux: {len(common['linux'])}), milliseconds, lower is better. Throughput: conversions a minute with 8 at "
            "once (synchronous API). Memory: peak MB with 8 at once, and the growth over 1,000 conversions in one process. "
            "Checks: content checks passed (text, images, fonts, page numbers, bookmarks, forms and others). Fidelity: "
            "mean similarity to a Chrome screenshot of the same page (1.0 = identical). Values are Windows / Linux.", ""]
    rows = []
    for l in html:
        cw, cl = checks(l, "windows"), checks(l, "linux")
        fw, fl = v[l][("fid", "windows")], v[l][("fid", "linux")]
        rows.append([f"{name[l]} {version[l]}",
                     pair(speed(l, "windows"), speed(l, "linux")),
                     pair(tp8(l, "windows"), tp8(l, "linux")),
                     pair(v[l][("mem8", "windows")], v[l][("mem8", "linux")]),
                     pair(growth(l, "windows"), growth(l, "linux"), lambda x: f"{x:+,.0f}"),
                     (f"{cw[0]} / {cl[0]} of {cw[1]}" if cw and cl and cw[1] == cl[1]
                      else pair(cw, cl, lambda c: f"{c[0]} of {c[1]}")),
                     pair(fw, fl, lambda x: f"{x:.3f}")])
    data["html"] = (["Library", "Speed, ms", "Throughput, ×8 /min", "Memory ×8, MB", "Memory over 1,000, MB",
                     "Checks", "Fidelity"], rows)
    out += [report.table(*data["html"]), ""]

    out += ["### Standards, PDF tasks and deployment", "",
            "Standards: PDF/A, PDF/UA and PDF/X levels produced that pass veraPDF (out of 17 requested). Tags: checks that "
            f"tagged files really contain headings, tables, lists and figures. Tasks: of the {len(TOOLS)} PDF tasks "
            "measured (text extraction, search, PDF to image, Word to PDF, redaction, merge, split, watermark, signature, "
            "form filling, ZUGFeRD), how many the library offers. Docker: the published app on "
            "`mcr.microsoft.com/dotnet/runtime:8.0`, as root and as a non-root user.", ""]
    rows = []
    for l in libs:
        produced, valid, asked = v[l]["standards"]
        st = v[l]["structure"]
        tools = sum(1 for t in TOOLS if v[l]["tools"].get(t) == "supported")
        rows.append([f"{name[l]} {version[l]}",
                     f"{valid}" if asked and produced else "–",
                     f"{st[0]}/{st[1]}" if st[1] else "–",
                     f"{v[l]['extract']:.2f}" if v[l]["extract"] is not None else "–",
                     f"{tools}",
                     docker(l),
                     fmt(v[l]["publish"].get("linux-x64"), 1)])
    data["std"] = (["Library", "Standards valid", "Tags", "Text extraction (lowest F1)", "PDF tasks",
                    "Docker", "Publish linux-x64, MB"], rows)
    out += [report.table(*data["std"]), ""]

    # Leaders: the best value of each measure, ties included; nothing is added up.
    def lead(label, f, pool, higher, show):
        vals = {l: f(l) for l in pool}
        vals = {l: x for l, x in vals.items() if x is not None}
        if not vals:
            return
        best = (max if higher else min)(vals.values())
        who = [l for l, x in vals.items() if x == best]
        out.append(f"- **{label}:** {', '.join(name[l] for l in who)} ({show(best)}).")
        data["leaders"].append((label, [name[l] for l in who], show(best)))

    out += ["### Leader of each measure", ""]
    for o in report.OSES:
        osn = report.OS_NAME[o]
        lead(f"Fastest HTML to PDF, {osn}", lambda l: speed(l, o), html, False, lambda x: f"{fmt(x)} ms")
        lead(f"Most conversions a minute with 8 at once, {osn}", lambda l: tp8(l, o), html, True, lambda x: fmt(x))
        lead(f"Lowest memory with 8 at once, {osn}", lambda l: v[l][("mem8", o)], html, False, lambda x: f"{fmt(x)} MB")
        lead(f"Least memory growth over 1,000 conversions, {osn}", lambda l: growth(l, o), libs, False,
             lambda x: f"{x:+,.0f} MB")
        lead(f"Most content checks passed, {osn}", lambda l: (lambda c: c[0] / c[1] if c else None)(checks(l, o)),
             html, True, lambda x: f"{x:.0%}")
    lead("Closest to Chrome (fidelity, Windows)", lambda l: v[l][("fid", "windows")], html, True, lambda x: f"{x:.3f}")
    lead("Most PDF/A, PDF/UA and PDF/X levels valid", lambda l: v[l]["standards"][1] if v[l]["standards"][2] else None,
         libs, True, lambda x: f"{x} of 17")
    lead("All tag-structure checks passed", lambda l: (v[l]["structure"][0] / v[l]["structure"][1]) if v[l]["structure"][1] else None,
         libs, True, lambda x: f"{x:.0%}")
    lead("Best text extraction", lambda l: v[l]["extract"], libs, True, lambda x: f"lowest F1 {x:.2f}")
    lead("Most PDF tasks offered", lambda l: sum(1 for t in TOOLS if v[l]["tools"].get(t) == "supported"), libs, True,
         lambda x: f"{x} of {len(TOOLS)}")
    lead("Smallest publish size, linux-x64", lambda l: v[l]["publish"].get("linux-x64"), libs, False,
         lambda x: f"{fmt(x, 1)} MB")
    out += ["", END]
    return "\n".join(out), data


def write_llms(data: dict, path: pathlib.Path, library: str = "SelectPdf"):
    """A Markdown block for a site's llms.txt: the leaders and one library's own row, as quotable sentences."""
    page = RESULTS_PAGE.format(run=data["run"])
    lines = ["## Benchmark results", "",
             f"Open benchmark of ten .NET PDF libraries on one machine, Windows and Linux, run {data['run']}; "
             f"maintained by SelectPdf, one of the libraries measured. Full results: {page}", ""]
    lines += [f"- {label}: {', '.join(who)} ({value})." for label, who, value in data["leaders"]]
    say = {"Speed, ms": "average time per page {} ms", "Throughput, ×8 /min": "{} conversions a minute with 8 at once",
           "Memory ×8, MB": "peak memory with 8 at once {} MB", "Memory over 1,000, MB": "memory growth over 1,000 conversions {} MB",
           "Checks": "content checks passed {}", "Fidelity": "fidelity to Chrome {}",
           "Standards valid": "{} of 17 PDF/A, PDF/UA and PDF/X levels valid", "Tags": "tag-structure checks passed {}",
           "Text extraction (lowest F1)": "text extraction lowest F1 {}", "PDF tasks": "{} of 11 PDF tasks offered",
           "Docker": "Docker: {}", "Publish linux-x64, MB": "publish size linux-x64 {} MB"}
    for (header, rows), what in ((data["html"], "HTML to PDF, Windows / Linux"), (data["std"], "standards, PDF tasks and deployment")):
        row = next((r for r in rows if r[0].startswith(library + " ")), None)
        if row:
            cells = "; ".join(say[h].format(c) for h, c in zip(header[1:], row[1:]) if c not in ("–", ""))
            lines.append(f"- {row[0]}, {what}: {cells}.")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote", path)


def write_html(data: dict, folder: pathlib.Path):
    """Three Razor partials for the site's library comparison page: the two tables and the leaders list."""
    import html as h
    note = f"@* Generated by csharp-pdf/pdf-benchmarks analysis/readme_summary.py --run {data['run']} --html; do not edit. *@"

    def table(header, rows):
        lines = [note, '<table class="spdf-howto-table">',
                 "  <thead><tr>" + "".join(f"<th>{h.escape(c)}</th>" for c in header) + "</tr></thead>", "  <tbody>"]
        lines += ["    <tr>" + "".join(f"<td>{h.escape(str(c))}</td>" for c in r) + "</tr>" for r in rows]
        return "\n".join(lines + ["  </tbody>", "</table>", ""])
    files = {"_LibrariesHtmlTable.cshtml": table(*data["html"]), "_LibrariesStandardsTable.cshtml": table(*data["std"])}
    items = [f"  <li><strong>{h.escape(label)}:</strong> {h.escape(', '.join(who))} ({h.escape(value)}).</li>"
             for label, who, value in data["leaders"]]
    files["_LibrariesLeaders.cshtml"] = "\n".join([note, '<ul class="spdf-howto-facts">'] + items + ["</ul>", ""])
    for fname, text in files.items():
        (folder / fname).write_text(text, encoding="utf-8", newline="\n")
        print("wrote", folder / fname)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--readme", action="append", default=[])
    ap.add_argument("--html", metavar="FOLDER", help="also write the site partials (_Libraries*.cshtml) into FOLDER")
    ap.add_argument("--llms", metavar="FILE", help="also write the benchmark block a site's llms.txt includes")
    ap.add_argument("--override", action="append", default=[])
    a = ap.parse_args()
    overrides = {}
    for o in a.override:
        left, folder = o.split("=")
        os_, lib = left.split(":")
        overrides[(os_, lib)] = folder
    section, data = build(report.Run(a.run, overrides), a.run)
    if a.html:
        write_html(data, pathlib.Path(a.html))
    if a.llms:
        write_llms(data, pathlib.Path(a.llms))
    for path in map(pathlib.Path, a.readme):
        text = path.read_text(encoding="utf-8")
        if START in text:
            text = text[:text.index(START)] + section + text[text.index(END) + len(END):]
        else:
            raise SystemExit(f"{path}: add the marker lines where the section goes:\n{START}\n{END}")
        path.write_text(text, encoding="utf-8", newline="\n")
        print("updated", path)


if __name__ == "__main__":
    main()
