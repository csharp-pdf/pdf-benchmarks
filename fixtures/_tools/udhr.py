"""Generates the rtl/ and cjk/ fixtures from the Universal Declaration of Human
Rights (UDHR in XML project, https://github.com/eric-muller/udhr).

The UDHR may be freely reproduced (United Nations). Output is committed.

    python fixtures/_tools/udhr.py
"""
import html
import pathlib
import urllib.request
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = "https://raw.githubusercontent.com/eric-muller/udhr/main/data/udhr/udhr_{}.xml"
NS = {"u": "http://efele.net/udhr"}
ARTICLES = 6   # preamble + articles 1-6: several paragraphs per language, more than one page


def load(code: str):
    with urllib.request.urlopen(SRC.format(code)) as r:
        root = ET.fromstring(r.read())
    title = root.findtext("u:title", namespaces=NS)
    pre = root.find("u:preamble", NS)
    paras = [("h2", pre.findtext("u:title", namespaces=NS) or "")] + [("p", p.text or "") for p in pre.findall("u:para", NS)]
    for art in root.findall("u:article", NS)[:ARTICLES]:
        paras.append(("h3", art.findtext("u:title", namespaces=NS) or ""))
        paras += [("p", p.text or "") for p in art.iter("{http://efele.net/udhr}para")]
    return title, paras


def section(code: str, lang: str, font: str, direction: str = "ltr") -> str:
    title, paras = load(code)
    body = "\n".join(f"    <{t}>{html.escape(s.strip())}</{t}>" for t, s in paras if s.strip())
    return (f'  <section lang="{lang}" dir="{direction}" style="font-family: \'{font}\', sans-serif">\n'
            f"    <h1>{html.escape(title or '')}</h1>\n{body}\n  </section>")


PAGE = """<!doctype html>
<html lang="{lang}" dir="{dir}">
<head>
<meta charset="utf-8">
<title>{title}</title>
<link rel="stylesheet" href="../_shared/fonts/fonts.css">
<style>
  body {{ margin: 32px; font-size: 16px; line-height: 1.7; color: #1d1d1f; }}
  h1 {{ font-size: 28px; margin: 0 0 16px; }}
  h2, h3 {{ margin: 24px 0 8px; }}
  section {{ margin-bottom: 48px; }}
  table {{ border-collapse: collapse; margin: 16px 0; }}
  td, th {{ border: 1px solid #c8c8cc; padding: 6px 12px; }}
</style>
</head>
<body>
{extra}
{sections}
</body>
</html>
"""

# A right-to-left table with left-to-right numbers and Latin words inside: bidi mixing.
RTL_TABLE = """  <table lang="ar" dir="rtl" style="font-family: 'Noto Sans Arabic', sans-serif">
    <tr><th>المادة</th><th>عدد الفقرات</th><th>ملاحظة</th></tr>
    <tr><td>1</td><td>1</td><td>PDF 2.0</td></tr>
    <tr><td>2</td><td>2</td><td>ISO 32000-2</td></tr>
    <tr><td>3</td><td>1</td><td>12.5%</td></tr>
  </table>"""

if __name__ == "__main__":
    rtl = PAGE.format(lang="ar", dir="rtl", title="rtl", extra=RTL_TABLE,
                      sections=section("arb", "ar", "Noto Sans Arabic", "rtl"))
    cjk = PAGE.format(lang="en", dir="ltr", title="cjk", extra="",
                      sections="\n".join([section("cmn_hans", "zh-Hans", "Noto Sans SC"),
                                          section("jpn", "ja", "Noto Sans JP"),
                                          section("kor", "ko", "Noto Sans KR")]))
    for name, text in (("rtl", rtl), ("cjk", cjk)):
        d = ROOT / name
        d.mkdir(exist_ok=True)
        (d / "index.html").write_text(text, encoding="utf-8")
        (d / "SOURCE.md").write_text(
            "Text: Universal Declaration of Human Rights (United Nations, freely reproducible), "
            "from the UDHR in XML project (https://github.com/eric-muller/udhr). "
            "Generated by `_tools/udhr.py`. Fonts: Noto Sans (SIL Open Font License), see `../_shared/fonts/`.\n",
            encoding="utf-8")
        print(name, len(text), "chars")
